/**
 * Zero-dependency OpenAPI -> TypeScript generator for @openrail/api-client.
 *
 * Generates component types and an `operations` map from
 * services/api/openapi.json. The thin client in src/client.ts is hand-written.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export interface OpenApiDocument {
  components?: { schemas?: Record<string, Schema>; parameters?: Record<string, Parameter> };
  paths?: Record<string, Record<string, Operation>>;
}

type Schema = {
  $ref?: string;
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  oneOf?: Schema[];
  anyOf?: Schema[];
  allOf?: Schema[];
  nullable?: boolean;
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: boolean | Schema;
  description?: string;
  [key: string]: unknown;
};

type Parameter = {
  $ref?: string;
  name?: string;
  in?: string;
  required?: boolean;
  schema?: Schema;
};

type Operation = {
  operationId?: string;
  parameters?: Parameter[];
  requestBody?: { required?: boolean; content?: Record<string, { schema?: Schema }> };
  responses?: Record<string, { content?: Record<string, { schema?: Schema }> }>;
};

const SPEC_URL = new URL("../../../services/api/openapi.json", import.meta.url);
const OUTPUT_URL = new URL("../src/generated.ts", import.meta.url);
const HEADER =
  "// GENERATED by scripts/generate.ts from services/api/openapi.json. Do not edit.\n// Run `pnpm --filter @openrail/api-client generate` after changing the OpenAPI document.\n\n";

function readSpec(): OpenApiDocument {
  return JSON.parse(readFileSync(SPEC_URL, "utf8")) as OpenApiDocument;
}

function refName(ref: string): string {
  return ref.split("/").pop() ?? ref;
}

function literal(value: unknown): string {
  return JSON.stringify(value) ?? "unknown";
}

function safeKey(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function objectType(schema: Schema, indent: string): string {
  const properties = Object.entries(schema.properties ?? {});
  if (properties.length === 0) {
    const extra = schema.additionalProperties;
    if (extra && typeof extra === "object") return `Record<string, ${typeExpr(extra, indent)}>`;
    return "Record<string, unknown>";
  }
  const required = new Set(schema.required ?? []);
  const lines = properties.map(([key, value]) => {
    const optional = required.has(key) ? "" : "?";
    return `${indent}  ${safeKey(key)}${optional}: ${typeExpr(value, `${indent}  `)};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function primitive(type: string, schema: Schema, indent: string): string {
  switch (type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = schema.items ? typeExpr(schema.items, indent) : "unknown";
      return item.includes("\n") ? `Array<${item}>` : `${item}[]`;
    }
    case "object":
      return objectType(schema, indent);
    default:
      return "unknown";
  }
}

function typeExpr(schema: Schema | undefined, indent: string): string {
  if (schema === undefined) return "unknown";
  if (schema.$ref !== undefined) return refName(schema.$ref);
  if ("const" in schema) return literal(schema.const);
  if (schema.enum !== undefined) return schema.enum.map(literal).join(" | ");
  const combinator = schema.oneOf ?? schema.anyOf;
  if (combinator !== undefined)
    return combinator.map((entry) => typeExpr(entry, indent)).join(" | ");
  if (schema.allOf !== undefined)
    return schema.allOf.map((entry) => typeExpr(entry, indent)).join(" & ");

  const types = Array.isArray(schema.type)
    ? schema.type
    : schema.type === undefined
      ? []
      : [schema.type];
  let result =
    types.length > 0
      ? types.map((type) => primitive(type, schema, indent)).join(" | ")
      : schema.properties !== undefined
        ? objectType(schema, indent)
        : schema.additionalProperties !== undefined
          ? objectType(schema, indent)
          : "unknown";
  if (schema.nullable === true && !result.includes("null")) result += " | null";
  return result;
}

function resolveParameter(parameter: Parameter, parameters: Record<string, Parameter>): Parameter {
  if (parameter.$ref === undefined) return parameter;
  return parameters[refName(parameter.$ref)] ?? parameter;
}

function parametersType(operation: Operation, document: OpenApiDocument): string | undefined {
  const all = document.components?.parameters ?? {};
  const groups = new Map<string, string[]>();
  for (const raw of operation.parameters ?? []) {
    const parameter = resolveParameter(raw, all);
    if (parameter.name === undefined || parameter.in === undefined) continue;
    const optional = parameter.required === true ? "" : "?";
    const line = `${safeKey(parameter.name)}${optional}: ${typeExpr(parameter.schema, "    ")};`;
    const group = groups.get(parameter.in) ?? [];
    group.push(line);
    groups.set(parameter.in, group);
  }
  if (groups.size === 0) return undefined;
  const lines = [...groups.entries()].map(
    ([where, entries]) =>
      `    ${where}: {\n${entries.map((entry) => `      ${entry}`).join("\n")}\n    };`,
  );
  return `{\n${lines.join("\n")}\n  }`;
}

function operationType(operation: Operation, document: OpenApiDocument): string {
  const parts: string[] = [];
  const parameters = parametersType(operation, document);
  if (parameters !== undefined) parts.push(`    parameters: ${parameters};`);
  const body = operation.requestBody?.content?.["application/json"]?.schema;
  if (body !== undefined) parts.push(`    requestBody: ${typeExpr(body, "    ")};`);
  const responses = Object.entries(operation.responses ?? {}).map(([status, response]) => {
    const schema = response.content?.["application/json"]?.schema;
    return `    ${JSON.stringify(status)}: ${typeExpr(schema, "    ")};`;
  });
  parts.push(`    responses: {\n${responses.join("\n")}\n    };`);
  return `{\n${parts.join("\n")}\n  }`;
}

/** Generate the TypeScript source for the given document. */
export function generateSource(document: OpenApiDocument = readSpec()): string {
  const schemas = document.components?.schemas ?? {};
  const lines: string[] = [HEADER.trimEnd(), ""];
  for (const [name, schema] of Object.entries(schemas)) {
    if (schema.type === "object" && schema.properties !== undefined && schema.oneOf === undefined) {
      lines.push(`export interface ${name} ${objectType(schema, "")}`);
    } else {
      lines.push(`export type ${name} = ${typeExpr(schema, "")};`);
    }
    lines.push("");
  }

  lines.push("export interface operations {");
  for (const pathItem of Object.values(document.paths ?? {})) {
    for (const operation of Object.values(pathItem)) {
      if (operation.operationId === undefined) continue;
      lines.push(`  ${safeKey(operation.operationId)}: ${operationType(operation, document)};`);
    }
  }
  lines.push("}");
  lines.push("");
  return `${lines.join("\n")}`;
}

/** Write src/generated.ts. */
export function writeGenerated(): void {
  writeFileSync(OUTPUT_URL, generateSource(), "utf8");
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  writeGenerated();
  console.log("wrote packages/api-client/src/generated.ts");
}
