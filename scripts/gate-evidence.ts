/**
 * Gate evidence writer. Turns the captured output of `scripts/gate-run.sh` into
 * `evidence/gate-g1-<UTC date>.md`. Every value is parsed from the log or from git;
 * nothing is typed by hand.
 *
 * Usage: tsx scripts/gate-evidence.ts <gate-log> <exit-code> <elapsed-seconds> [out-file]
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// eslint-disable-next-line no-control-regex
const ANSI = /\u001b\[[0-9;]*m/g;

const STAGES = [
  { id: "0", name: "Build contract WASM", target: "cargo near build non-reproducible-wasm" },
  { id: "1", name: "Proptests", target: "openrail-model --test proptest_invariants" },
  { id: "2", name: "Scale suite", target: "openrail-tests --test scale_suite" },
  {
    id: "3",
    name: "Mutation spot checks",
    target: "openrail-model --test mutation_checks; openrail-tests --test mutation_tests",
  },
  { id: "4", name: "Deploy rehearsal", target: "scripts/deploy/rehearse.sh" },
];

function git(cmd: string, root: string): string {
  return execSync(`git ${cmd}`, { cwd: root, encoding: "utf8" }).trim();
}

export function buildEvidence(
  log: string,
  exitCode: number,
  elapsedSeconds: number,
  root: string,
  now = new Date(),
): string {
  const text = log.replace(ANSI, "").replace(/\r/g, "");
  const lines = text.split("\n");

  // Split the log into stage sections by the `=== [n/4] ... ===` headers.
  const sections = new Map<string, string[]>();
  let current: string | null = null;
  const elapsed = new Map<string, string>();
  for (const line of lines) {
    const header = /^=== \[(\d)\/4\]/.exec(line);
    if (header?.[1] !== undefined) {
      current = header[1];
      sections.set(current, []);
      continue;
    }
    const done = /^\[stage-result\] (\d) elapsed=(\d+s)/.exec(line);
    if (done?.[1] !== undefined && done[2] !== undefined) elapsed.set(done[1], done[2]);
    if (current !== null) sections.get(current)?.push(line);
  }

  const rows: string[] = [];
  for (const s of STAGES) {
    const body = sections.get(s.id);
    const finished = elapsed.has(s.id);
    let passed = 0;
    let failed = 0;
    let ignored = 0;
    for (const l of body ?? []) {
      const m = /^test result: (ok|FAILED)\. (\d+) passed; (\d+) failed; (\d+) ignored/.exec(l);
      if (m !== null) {
        passed += Number(m[2]);
        failed += Number(m[3]);
        ignored += Number(m[4]);
      }
    }
    const counts =
      s.id === "0" || s.id === "4"
        ? "n/a"
        : `${passed} passed, ${failed} failed, ${ignored} ignored`;
    const result = finished && failed === 0 ? "PASS" : body === undefined ? "NOT RUN" : "FAIL";
    rows.push(
      `| ${s.id} | ${s.name} | \`${s.target}\` | ${result} | ${elapsed.get(s.id) ?? "-"} | ${counts} |`,
    );
  }

  const figures = lines.filter((l) =>
    /^(scale_[a-z_]+ at N=|claims_by_issuer at N=|nft_token.* at N=)/.test(l),
  );

  const config = (key: string): string => {
    const m = new RegExp(`^\\s+${key}\\s*:\\s*(\\S+)`, "m").exec(text);
    return m?.[1] ?? "unknown";
  };

  const head = git("rev-parse HEAD", root);
  const mainRef = git("rev-parse origin/main", root);
  const dirty = git("status --porcelain", root) === "" ? "clean" : "DIRTY";
  const overall = exitCode === 0 ? "PASS" : `FAIL (exit ${exitCode})`;
  const date = now.toISOString().slice(0, 10);

  const out: string[] = [];
  out.push(`# Gate G1 run ${date}`);
  out.push("");
  out.push(
    "Generated by `scripts/gate-evidence.ts` from the captured output of `scripts/gate-run.sh`.",
  );
  out.push("No value in this file was edited by hand.");
  out.push("");
  out.push("## Run");
  out.push("");
  out.push(`- Result: **${overall}**`);
  out.push(`- Finished (UTC): ${now.toISOString()}`);
  out.push(`- Total elapsed: ${elapsedSeconds}s`);
  out.push(`- Commit: \`${head}\` (working tree ${dirty})`);
  out.push(`- \`origin/main\` at run time: \`${mainRef}\``);
  out.push(`- Proptest cases: ${config("Proptest cases")}`);
  out.push(`- Scale claims: ${config("Scale claims")}`);
  out.push("");
  out.push("## Stages");
  out.push("");
  out.push("| Stage | Name | Target | Result | Elapsed | Test counts |");
  out.push("| ----- | ---- | ------ | ------ | ------- | ----------- |");
  out.push(...rows);
  out.push("");
  out.push("## How the scale numbers were produced");
  out.push("");
  out.push(
    "The sample points (claims 1, N/10, N/2 and N) are real transactions. Claims between sample",
  );
  out.push(
    "points were seeded directly into contract state with `worker.patch` (same key layout as",
  );
  out.push(
    "`issue`), not issued by transactions. Gas is `total_gas_burnt` of the transaction; storage",
  );
  out.push("is the change in the root account's `storage_usage` around the sample-point `issue`.");
  out.push("");
  out.push("## Scale figures (as printed by `scale_suite`)");
  out.push("");
  out.push("```text");
  out.push(...(figures.length > 0 ? figures : ["(no figures found in log)"]));
  out.push("```");
  out.push("");
  return out.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const [logPath, code, secs, outArg] = process.argv.slice(2);
  if (logPath === undefined || code === undefined || secs === undefined) {
    console.error("usage: gate-evidence.ts <gate-log> <exit-code> <elapsed-seconds> [out-file]");
    process.exit(2);
  }
  const now = new Date();
  const md = buildEvidence(readFileSync(logPath, "utf8"), Number(code), Number(secs), root, now);
  const out = outArg ?? resolve(root, `evidence/gate-g1-${now.toISOString().slice(0, 10)}.md`);
  writeFileSync(out, md);
  console.log(`wrote ${out}`);
}
